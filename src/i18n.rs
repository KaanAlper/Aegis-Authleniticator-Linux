//! Translations. Generated table: one `Strings` block per language.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    En,
    Tr,
    De,
    Fr,
    Es,
    It,
    Pt,
    Ru,
    Pl,
}

impl Lang {
    pub const ALL: [Lang; 9] = [Lang::En, Lang::Tr, Lang::De, Lang::Fr, Lang::Es, Lang::It, Lang::Pt, Lang::Ru, Lang::Pl];

    /// Picks the first non-empty, non-"C" locale variable (LC_ALL, LC_MESSAGES, LANG).
    pub fn detect_system() -> Self {
        for var in ["LC_ALL", "LC_MESSAGES", "LANG"] {
            if let Ok(v) = std::env::var(var) {
                let v = v.trim().to_ascii_lowercase();
                if v.is_empty() || v == "c" || v == "posix" || v.starts_with("c.") {
                    continue;
                }
                return Self::from_code(&v);
            }
        }
        Lang::En
    }

    pub fn from_code(code: &str) -> Self {
        let lower = code.to_ascii_lowercase();
        match lower.get(..2).unwrap_or("") {
            "tr" => Lang::Tr,
            "de" => Lang::De,
            "fr" => Lang::Fr,
            "es" => Lang::Es,
            "it" => Lang::It,
            "pt" => Lang::Pt,
            "ru" => Lang::Ru,
            "pl" => Lang::Pl,
            _ => Lang::En,
        }
    }

    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Tr => "tr",
            Lang::De => "de",
            Lang::Fr => "fr",
            Lang::Es => "es",
            Lang::It => "it",
            Lang::Pt => "pt",
            Lang::Ru => "ru",
            Lang::Pl => "pl",
        }
    }

    pub fn native_name(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::Tr => "Türkçe",
            Lang::De => "Deutsch",
            Lang::Fr => "Français",
            Lang::Es => "Español",
            Lang::It => "Italiano",
            Lang::Pt => "Português",
            Lang::Ru => "Русский",
            Lang::Pl => "Polski",
        }
    }
}

